// dialogCommands are the commands of dialog NPCs: talk, menus, waits,
// pictures and emotions, without changes to the player.
var dialogCommands = map[string]bool{
	"mes": true, "next": true, "close": true, "close2": true, "close3": true, "end": true, "select": true,
	"menu": true, "goto": true, "cutin": true, "emotion": true, "npctalk": true, "strcharinfo": true,
	"rand": true, "sleep2": true, "variables": false, "input": true, "prompt": true, "random": true,
}

// isDialog reports whether an NPC only talks.
func (n *NPC) isDialog() bool {
	if n.Kind != "script" || len(n.Functions) > 0 {
		return false
	}
	for f := range n.Features {
		if !dialogCommands[f] {
			return false
		}
	}
	return true
}

// isKafra reports whether an NPC runs rAthena's Kafra services.
func (n *NPC) isKafra() bool {
	for _, f := range n.Functions {
		if f == "f_kafra" {
			return true
		}
	}
	return false
}

// isJobNPC reports whether an NPC comes from a jobs folder of rAthena's
// npc/: the job change NPCs.
func (n *NPC) isJobNPC() bool { return strings.Contains(n.File, "/jobs/") }

// NPCReport writes the coverage report of converted NPCs as Markdown:
// per kind, per command, per file, and per function.
func (r *NPCResult) NPCReport() string {
	var b strings.Builder
	fmt.Fprintf(&b, "# NPC script coverage: %s\n\n", r.Mode)
	b.WriteString("Generated by `wactl convert npcs --report`; do not edit. `go test ./tools/convert` checks that it is current.\n\n")
	b.WriteString("A script NPC is placed when its own script converts whole. It converts fully when the functions it calls convert whole too, and partly when a function has parts that fail when a script reaches them. Shops and barter shops become data in core's `data/npcs.yml`. A shop converts partly when some of its items do not convert.\n\n")

	type counts struct{ total, placed, full, partial, none int }
	byKind := map[string]*counts{}
	var kinds []string
	var kafras, dialogs, jobNPCs counts
	for _, n := range r.NPCs {
		kind := n.Kind
		if n.DuplicateOf != "" {
			kind += " (duplicate)"
		}
		c := byKind[kind]
		if c == nil {
			c = &counts{}
			byKind[kind] = c
			kinds = append(kinds, kind)
		}
		add := func(c *counts) {
			c.total++
			if n.Placed && n.Status != None {
				c.placed++
			}
			switch n.Status {
			case Full:
				c.full++
			case Partial:
				c.partial++
			default:
				c.none++
			}
		}
		add(c)
		if n.isKafra() {
			add(&kafras)
		}
		if n.isDialog() {
			add(&dialogs)
		}
		if n.Kind == "script" && n.DuplicateOf == "" && n.isJobNPC() {
			add(&jobNPCs)
		}
	}
	sort.Strings(kinds)
	b.WriteString("## NPC lines\n\n")
	b.WriteString("| Kind | Lines | Placed | Full | Partly | Not |\n|---|---:|---:|---:|---:|---:|\n")
	for _, k := range kinds {
		c := byKind[k]
		fmt.Fprintf(&b, "| %s | %d | %d | %d | %d | %d |\n", k, c.total, c.placed, c.full, c.partial, c.none)
	}
	fmt.Fprintf(&b, "| Kafras (scripts that call F_Kafra) | %d | %d | %d | %d | %d |\n", kafras.total, kafras.placed, kafras.full, kafras.partial, kafras.none)
	fmt.Fprintf(&b, "| Dialog NPCs (only talk, menus and emotions) | %d | %d | %d | %d | %d |\n", dialogs.total, dialogs.placed, dialogs.full, dialogs.partial, dialogs.none)
	fmt.Fprintf(&b, "| Job change NPCs (script NPCs of the jobs folders) | %d | %d | %d | %d | %d |\n\n", jobNPCs.total, jobNPCs.placed, jobNPCs.full, jobNPCs.partial, jobNPCs.none)
	b.WriteString("- Shops that are not placed have no map or no sprite: scripts open them with `callshop`, which converts to `player:open_shop`.\n")
	b.WriteString("- cashshop, itemshop, pointshop, marketshop and barter shops become shops with a cost and a stock. Players cannot sell to them, as in rAthena.\n")
	b.WriteString("- A cashshop's price is in cash points only. rAthena also lets Kafra points pay part of it, which does not convert.\n")
	b.WriteString("- A pointshop's variable becomes a currency: #CASHPOINTS is `cash`, #KAFRAPOINTS is `kafra`, and other variables are new records of core's `data/currencies.yml`. Reads and changes of these variables use the currency calls.\n")
	b.WriteString("- A barter item that is refined, that takes refined items or more than 5 kinds of items, or that the barter sells a second time, does not convert.\n")
	fmt.Fprintf(&b, "- %d currencies were added for pointshop variables.\n", len(r.conv.newCurrencies))
	b.WriteString("- Pushcart rental says it is not available yet.\n")
	fmt.Fprintf(&b, "- rAthena's getitem and delitem do nothing for an amount of 0 or less, and wAthena's calls raise an error. %d scripts and functions have a fixed amount of 0 or less, which converts to nothing. %d have a computed amount, which `R.give_item` and `R.take_item` check first.\n\n", len(r.conv.zeroAmounts), len(r.conv.checkedAmounts))
	if len(r.LeftOut) > 0 {
		b.WriteString("Script NPCs of these folders are not in the extract yet (reference/rathena/README.md, \"NPCs\"):\n\n| Folder | Script NPCs |\n|---|---:|\n")
		var folders []string
		for f := range r.LeftOut {
			folders = append(folders, f)
		}
		sort.Strings(folders)
		for _, f := range folders {
			fmt.Fprintf(&b, "| %s | %d |\n", f, r.LeftOut[f])
		}
		b.WriteString("\n")
	}

	b.WriteString("## Commands\n\n")
	b.WriteString("Counts are of script NPCs that are not duplicates, and of the functions they call.\n\n")
	r.npcFeatureTable(&b)

	b.WriteString("## Functions\n\n")
	b.WriteString("| Function | File | Converts | Parts that fail when reached |\n|---|---|---|---|\n")
	for _, f := range r.sortedFunctions() {
		status := "whole"
		switch {
		case f.Err != "":
			status = "no: " + escapeCell(f.Err)
		case len(f.Stubs) > 0:
			status = "partly"
		}
		fmt.Fprintf(&b, "| %s | %s:%d | %s | %s |\n", f.Name, f.File, f.Line, status, escapeCell(strings.Join(uniqueSorted(f.Stubs), "; ")))
	}
	b.WriteString("\n## Files\n\n")
	b.WriteString("| File | Lines | Placed | Not converted |\n|---|---:|---:|---:|\n")
	type fc struct{ total, placed, none int }
	files := map[string]*fc{}
	var names []string
	for _, n := range r.NPCs {
		c := files[n.File]
		if c == nil {
			c = &fc{}
			files[n.File] = c
			names = append(names, n.File)
		}
		c.total++
		if n.Placed && n.Status != None {
			c.placed++
		}
		if n.Status == None {
			c.none++
		}
	}
	sort.Strings(names)
	for _, f := range names {
		c := files[f]
		fmt.Fprintf(&b, "| %s | %d | %d | %d |\n", f, c.total, c.placed, c.none)
	}
	return b.String()
}

func uniqueSorted(list []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range list {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	sort.Strings(out)
	return out
}

// npcFeatureTable writes one row per command: the scripts that use it,
// how they converted, and why the command did not convert.
func (r *NPCResult) npcFeatureTable(b *strings.Builder) {
	type row struct {
		feature                     string
		scripts, full, partial, not int
		converted                   int
		reasons                     map[string]int
	}
	rows := map[string]*row{}
	for _, n := range r.NPCs {
		if n.Kind != "script" || n.DuplicateOf != "" {
			continue
		}
		features := map[string]bool{}
		for f, ok := range n.Features {
			features[f] = ok
		}
		for _, fn := range n.Functions {
			if f := r.Functions[fn]; f != nil {
				for g, ok := range f.Features {
					if prev, seen := features[g]; !seen || prev {
						features[g] = ok
					}
				}
			}
		}
		for f, ok := range features {
			x := rows[f]
			if x == nil {
				x = &row{feature: f, reasons: map[string]int{}}
				rows[f] = x
			}
			x.scripts++
			switch n.Status {
			case Full:
				x.full++
			case Partial:
				x.partial++
			default:
				x.not++
			}
			if ok {
				x.converted++
				continue
			}
			for _, u := range n.Unsupported {
				if u == f || strings.HasPrefix(u, f+":") {
					x.reasons[strings.TrimPrefix(strings.TrimPrefix(u, f), ": ")]++
				}
			}
		}
	}
	list := make([]*row, 0, len(rows))
	for _, x := range rows {
		list = append(list, x)
	}
	sort.Slice(list, func(i, j int) bool {
		if list[i].scripts != list[j].scripts {
			return list[i].scripts > list[j].scripts
		}
		return list[i].feature < list[j].feature
	})
	b.WriteString("| Command | Scripts | NPC full | NPC partly | NPC not | This part converts | Why not |\n|---|---:|---:|---:|---:|---:|---|\n")
	for _, x := range list {
		type kv struct {
			k string
			v int
		}
		var reasons []kv
		for k, v := range x.reasons {
			if k != "" {
				reasons = append(reasons, kv{k, v})
			}
		}
		sort.Slice(reasons, func(i, j int) bool {
			if reasons[i].v != reasons[j].v {
				return reasons[i].v > reasons[j].v
			}
			return reasons[i].k < reasons[j].k
		})
		var why []string
		for i, rr := range reasons {
			if i == 3 {
				break
			}
			why = append(why, fmt.Sprintf("%s (%d)", escapeCell(rr.k), rr.v))
		}
		fmt.Fprintf(b, "| %s | %d | %d | %d | %d | %d | %s |\n", x.feature, x.scripts, x.full, x.partial, x.not, x.converted, strings.Join(why, "; "))
	}
	b.WriteString("\n")
}

// NPCSummary is one line about the conversion, for logs.
func (r *NPCResult) NPCSummary() string {
	placed, shops, scripts := 0, 0, 0
	for _, n := range r.NPCs {
		if n.Placed && n.Status != None {
			placed++
			if n.Shop {
				shops++
			} else {
				scripts++
			}
		}
	}
	return fmt.Sprintf("%s: %d NPCs placed, %d shops and %d script NPCs, of %d NPC lines", r.Mode, placed, shops, scripts, len(r.NPCs))
}
