package convert

import (
	"fmt"
	"sort"
	"strings"
)

// ClassicNotesPath is where the release notes list of classic mode is
// kept, from the repository's root.
const ClassicNotesPath = "docs/generated/classic-coverage.md"

// classicTopReasons is how many reasons the list of what blocks the
// rest shows.
const classicTopReasons = 30

// npcToNPC are the reasons of the NPC-to-NPC commands, which convert
// since review decision 58, except some forms.
var npcToNPC = map[string]bool{
	"donpcevent": true, "doevent": true, "cmdothernpc": true, "enablenpc": true, "disablenpc": true,
	"cloakonnpc": true, "cloakoffnpc": true, "cloakonnpcself": true, "cloakoffnpcself": true,
	"hideonnpc": true, "hideoffnpc": true, "getvariableofnpc": true, "isnpccloaked": true, "unloadnpc": true,
}

// blockReason is the reason a script NPC is not placed, for the release
// notes: the part of its first unsupported entry before the colon, with
// timer labels as one.
func blockReason(n *NPC) string {
	if len(n.Unsupported) == 0 {
		return "unknown"
	}
	f, _, _ := strings.Cut(n.Unsupported[0], ":")
	if strings.HasPrefix(f, "event ontimer") {
		return "event ontimer<n>"
	}
	return f
}

// ClassicNotes writes the release notes list of classic mode
// (review decision 55): what does not convert in a classic world with
// mode renewal, from the coverage of r, which must be renewal's. It has
// the NPC lines by folder, what blocks the script NPCs that are not
// placed, and the systems that are not built.
func (r *NPCResult) ClassicNotes() string {
	var b strings.Builder
	b.WriteString("# Classic mode: what does not convert\n\n")
	b.WriteString("Generated by `wactl convert classic --report " + ClassicNotesPath + "`; do not edit. `go test ./tools/convert` checks that it is current.\n\n")
	fmt.Fprintf(&b, "This is the list for the release notes of classic mode, which ships with `mode: %s` (review decision 55). It comes from the converter's coverage of rAthena's NPC scripts, which [npc-scripts-%s.md](npc-scripts-%s.md) has in full.\n\n", r.Mode, r.Mode, r.Mode)

	type counts struct{ total, placed int }
	var all, scripts, shops, kafras, jobs counts
	partly := 0
	byFolder := map[string]*counts{}
	reasons := map[string]int{}
	details := map[string]map[string]int{}
	notPlaced := 0
	for _, n := range r.NPCs {
		placed := n.Placed && n.Status != None
		add := func(c *counts) {
			c.total++
			if placed {
				c.placed++
			}
		}
		add(&all)
		switch {
		case n.Kind == "script":
			add(&scripts)
			f := npcFolder(n.File)
			if byFolder[f] == nil {
				byFolder[f] = &counts{}
			}
			add(byFolder[f])
			if placed && n.Status == Partial {
				partly++
			}
			if n.isKafra() {
				add(&kafras)
			}
			if n.DuplicateOf == "" && n.isJobNPC() {
				add(&jobs)
			}
			if !placed && n.DuplicateOf == "" {
				notPlaced++
				k := blockReason(n)
				reasons[k]++
				if details[k] == nil {
					details[k] = map[string]int{}
				}
				if len(n.Unsupported) > 0 {
					details[k][n.Unsupported[0]]++
				}
			}
		case n.Placed:
			add(&shops)
		}
	}

	b.WriteString("## Summary\n\n")
	fmt.Fprintf(&b, "- %d of %d NPC lines are placed, duplicates too: %d shops and %d of %d script NPCs.\n", all.placed, all.total, shops.placed, scripts.placed, scripts.total)
	fmt.Fprintf(&b, "- %d placed script NPCs convert partly: a function they call has parts that fail when a script reaches them.\n", partly)
	fmt.Fprintf(&b, "- %d of %d Kafras are placed. Every placed Kafra converts fully, with storage, teleport, save, pushcart rental and Niflheim's HP and SP loss.\n", kafras.placed, kafras.total)
	fmt.Fprintf(&b, "- %d of %d job change NPCs are placed: the script NPCs of the jobs folders, duplicates left out.\n", jobs.placed, jobs.total)
	b.WriteString("- Pre-renewal classic is experimental until `core.ruleset.pre_renewal` matches rAthena's pre-renewal (phase 10 item 1). `waserver` warns at start.\n\n")

	b.WriteString("## Folders\n\n")
	b.WriteString("Script NPC lines, duplicates too, by the folder of their file below `npc/` and `npc/re/`.\n\n")
	b.WriteString("| Folder | Lines | Placed | Not placed |\n|---|---:|---:|---:|\n")
	for _, f := range sortedKeys(byFolder) {
		c := byFolder[f]
		fmt.Fprintf(&b, "| %s | %d | %d | %d |\n", f, c.total, c.placed, c.total-c.placed)
	}
	b.WriteString("\n")
	if len(r.LeftOut) > 0 {
		b.WriteString("The extract leaves out the script NPCs of these folders, so none of them load:\n\n| Folder | Script NPCs |\n|---|---:|\n")
		for _, f := range sortedKeys(r.LeftOut) {
			fmt.Fprintf(&b, "| %s | %d |\n", f, r.LeftOut[f])
		}
		b.WriteString("\n")
	}

	type kv struct {
		k string
		v int
	}
	list := make([]kv, 0, len(reasons))
	toNPC := 0
	for k, v := range reasons {
		list = append(list, kv{k, v})
		if npcToNPC[k] {
			toNPC += v
		}
	}
	sort.Slice(list, func(i, j int) bool {
		if list[i].v != list[j].v {
			return list[i].v > list[j].v
		}
		return list[i].k < list[j].k
	})
	b.WriteString("## What blocks the rest\n\n")
	fmt.Fprintf(&b, "%d script NPCs that are not duplicates are not placed. Each counts once, for the first part of its script that does not convert. A duplicate is placed when its source is. The %d most common reasons:\n\n", notPlaced, min(classicTopReasons, len(list)))
	b.WriteString("| Reason | Scripts | Most common entry of the coverage report |\n|---|---:|---|\n")
	for i, x := range list {
		if i == classicTopReasons {
			break
		}
		fmt.Fprintf(&b, "| %s | %d | %s |\n", escapeCell(x.k), x.v, escapeCell(mostCommon(details[x.k])))
	}
	b.WriteString("\n")
	b.WriteString("- `event <label>` is a label that rAthena runs on its own, such as `OnPCLogoutEvent` or `OnAgitStart`. Every other label converts to an `npc_event` handler (review decision 58).\n")
	b.WriteString("- `parameter <name>` reads or changes a player parameter that does not convert, such as `MaxWeight`.\n")
	b.WriteString("- `floating` is a script NPC without a map whose script does nothing. Other NPCs without a map are placed, and run in the start map's zone (review decision 58). `instance` is an NPC on an instance map. `sprite` is a view that is not an NPC sprite.\n")
	fmt.Fprintf(&b, "- The NPC-to-NPC commands (`donpcevent`, `doevent`, enable and disable, cloaking and hiding, `getvariableofnpc`, `unloadnpc`) convert since review decision 58. The forms that do not, such as `doevent` to an NPC on another map, block %d of these scripts.\n\n", toNPC)

	b.WriteString("## Systems not built\n\n")
	b.WriteString("These systems are not in the first release, so their NPCs do not load. They are in phase 10.\n\n")
	b.WriteString("| System | rAthena's NPCs | Script NPCs |\n|---|---|---:|\n")
	inst := r.LeftOut["instances"]
	if c := byFolder["instances"]; c != nil {
		inst += c.total
	}
	guilds := r.LeftOut["guild"] + r.LeftOut["guild2"] + r.LeftOut["guild3"]
	if c := byFolder["guild3"]; c != nil {
		guilds += c.total
	}
	fmt.Fprintf(&b, "| Instances (memorial dungeons) | `npc/re/instances` and the instance maps of other folders | %d |\n", inst)
	fmt.Fprintf(&b, "| Sieges (War of Emperium guild castles) | `npc/guild`, `npc/guild2` and `npc/re/guild3` | %d |\n", guilds)
	fmt.Fprintf(&b, "| Battlegrounds | `npc/battleground` | %d |\n", r.LeftOut["battleground"])
	b.WriteString("| MVP tomb | `mvp_tomb_enabled` in `conf/battle/monster.conf`, which `mob_dead` places | none |\n\n")
	b.WriteString("- The counts are script NPC lines, duplicates too, in the extract and left out of it.\n")
	b.WriteString("- MVPs are still announced as rAthena does: the MVP effect and the MVP's prize line (decision 0051).\n")
	return b.String()
}

// mostCommon is the key with the highest count, the first in order on a
// tie.
func mostCommon(m map[string]int) string {
	best, n := "", 0
	for _, k := range sortedKeys(m) {
		if m[k] > n {
			best, n = k, m[k]
		}
	}
	return best
}
