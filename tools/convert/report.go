package convert

import (
	"fmt"
	"sort"
	"strings"
)

// Report writes the coverage report of a converted item database as
// Markdown: per kind of item, per command, and per bonus type, how many
// scripts convert fully, partly, or not, with the reasons.
func (r *Result) Report() string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Item script coverage: %s\n\n", r.Mode)
	b.WriteString("Generated by `wactl convert items --report`; do not edit. `go test ./tools/convert` checks that it is current.\n\n")
	b.WriteString("An item converts fully when every part of its scripts converts. A usable item that does not convert fully is refused when used, and the player is told what it needs. An equipment item that converts partly keeps the parts that converted.\n\n")

	kinds := []Kind{KindEquip, KindUsable, KindDelayed}
	type counts struct{ total, full, partial, none, static, lua int }
	byKind := map[Kind]*counts{}
	for _, k := range kinds {
		byKind[k] = &counts{}
	}
	for _, it := range r.Items {
		c := byKind[it.Kind]
		c.total++
		switch it.Status {
		case Full:
			c.full++
		case Partial:
			c.partial++
		default:
			c.none++
		}
		if it.Bonuses != nil {
			c.static++
		}
		if it.Lua != "" {
			c.lua++
		}
	}
	b.WriteString("## Items\n\n")
	b.WriteString("| Kind | Items with scripts | Full | Partly | Not | Static data | Lua files |\n|---|---:|---:|---:|---:|---:|---:|\n")
	names := map[Kind]string{KindEquip: "Equipment and cards", KindUsable: "Usable", KindDelayed: "Delayed use"}
	for _, k := range kinds {
		c := byKind[k]
		fmt.Fprintf(&b, "| %s | %d | %d (%s) | %d | %d | %d | %d |\n", names[k], c.total, c.full, pct(c.full, c.total), c.partial, c.none, c.static, c.lua)
	}
	b.WriteString("\n- Static data: equipment whose scripts are only constant bonuses. They become `bonuses` in item data, and the server applies them without Lua.\n")
	b.WriteString("- Lua files: items with an entry script, in `scripts/items/`.\n\n")

	for _, k := range kinds {
		fmt.Fprintf(&b, "## %s\n\n", names[k])
		r.featureTable(&b, k, func(f string) bool { return !strings.HasPrefix(f, "bonus") || !strings.Contains(f, " ") })
		if k == KindEquip {
			b.WriteString("### Bonus types\n\n")
			r.featureTable(&b, k, func(f string) bool { return strings.HasPrefix(f, "bonus") && strings.Contains(f, " ") })
		}
	}
	return b.String()
}

func pct(n, total int) string {
	if total == 0 {
		return "0%"
	}
	return fmt.Sprintf("%.1f%%", float64(n)*100/float64(total))
}

// featureTable writes one row per feature of a kind: the scripts that
// use it, how those items converted, whether the feature itself
// converted, and the most common reasons it did not.
func (r *Result) featureTable(b *strings.Builder, k Kind, keep func(string) bool) {
	type row struct {
		feature                     string
		scripts, full, partial, not int
		converted                   int
		reasons                     map[string]int
	}
	rows := map[string]*row{}
	for _, it := range r.Items {
		if it.Kind != k {
			continue
		}
		for f, ok := range it.Features {
			if !keep(f) {
				continue
			}
			x := rows[f]
			if x == nil {
				x = &row{feature: f, reasons: map[string]int{}}
				rows[f] = x
			}
			x.scripts++
			switch it.Status {
			case Full:
				x.full++
			case Partial:
				x.partial++
			default:
				x.not++
			}
			if ok {
				x.converted++
				continue
			}
			for _, u := range it.Unsupported {
				if u == f || strings.HasPrefix(u, f+":") || strings.HasPrefix(u, f+" ") {
					x.reasons[strings.TrimPrefix(strings.TrimPrefix(u, f), ": ")]++
				}
			}
		}
	}
	list := make([]*row, 0, len(rows))
	for _, x := range rows {
		list = append(list, x)
	}
	sort.Slice(list, func(i, j int) bool {
		if list[i].scripts != list[j].scripts {
			return list[i].scripts > list[j].scripts
		}
		return list[i].feature < list[j].feature
	})
	b.WriteString("| Command | Scripts | Item full | Item partly | Item not | This part converts | Why not |\n|---|---:|---:|---:|---:|---:|---|\n")
	for _, x := range list {
		var why []string
		type kv struct {
			k string
			v int
		}
		var reasons []kv
		for r, n := range x.reasons {
			reasons = append(reasons, kv{r, n})
		}
		sort.Slice(reasons, func(i, j int) bool {
			if reasons[i].v != reasons[j].v {
				return reasons[i].v > reasons[j].v
			}
			return reasons[i].k < reasons[j].k
		})
		for i, r := range reasons {
			if i == 3 {
				why = append(why, "...")
				break
			}
			text := r.k
			if text == "" {
				text = "not supported"
			}
			why = append(why, fmt.Sprintf("%s (%d)", escapeCell(text), r.v))
		}
		fmt.Fprintf(b, "| `%s` | %d | %d | %d | %d | %d | %s |\n", x.feature, x.scripts, x.full, x.partial, x.not, x.converted, strings.Join(why, "; "))
	}
	b.WriteString("\n")
}

func escapeCell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	if len(s) > 120 {
		s = s[:117] + "..."
	}
	return s
}

// Summary is a few lines with the counts of each kind.
func (r *Result) Summary() string {
	type counts struct{ total, full, partial, none, static int }
	byKind := map[Kind]*counts{}
	for _, it := range r.Items {
		c := byKind[it.Kind]
		if c == nil {
			c = &counts{}
			byKind[it.Kind] = c
		}
		c.total++
		switch it.Status {
		case Full:
			c.full++
		case Partial:
			c.partial++
		default:
			c.none++
		}
		if it.Bonuses != nil {
			c.static++
		}
	}
	var b strings.Builder
	for _, k := range []Kind{KindEquip, KindUsable, KindDelayed} {
		c := byKind[k]
		if c == nil {
			continue
		}
		fmt.Fprintf(&b, "%s: %d items with scripts, %d full, %d partly, %d not, %d static\n", k, c.total, c.full, c.partial, c.none, c.static)
	}
	return b.String()
}
